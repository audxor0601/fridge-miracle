/**
 * 레시피 제목에서 유튜브 검색어를 만든다.
 *
 * 공공 DB 제목은 대부분 그대로 써도 되지만, 일부는 설명이 길게 붙어 있다.
 *   "저염 된장으로 맛을 낸 황태해장국" → "황태해장국"
 * 1,156건에 돌려보니 손봐야 하는 건 36건뿐이었다. 나머지는 이미 짧다.
 *
 * API는 쓰지 않는다. 검색 결과 페이지로 보내기만 한다.
 * (YouTube Data API는 기본 할당량이 하루 search.list 100회라 나중에 필요해지면 그때 붙인다)
 */

/** 요리 이름의 꼬리. 긴 것부터 검사해야 '해장국'이 '국'보다 먼저 걸린다 */
const DISH_SUFFIX = [
  '해장국', '김치찌개', '된장찌개', '순두부찌개', '부대찌개', '찌개', '전골',
  '칼국수', '국수', '수제비', '볶음밥', '비빔밥', '주먹밥', '덮밥', '리조또',
  '미역국', '무국', '해장탕', '죽', '밥', '국', '탕', '볶음', '구이', '조림',
  '찜', '무침', '초무침', '냉채', '절임', '장아찌', '튀김', '전', '말이', '쌈',
  '샐러드', '스프', '수프', '파스타', '스파게티', '피자', '샌드위치', '토스트',
  '버거', '만두', '떡볶이', '잡채', '강정', '꼬치', '탕수육', '까스', '스테이크',
  '크로켓', '카나페', '라떼', '주스', '스무디', '피클', '소박이', '겉절이',
  '나물', '쿠키', '케이크', '머핀', '빵', '떡', '김치', '롤', '갈비',
].sort((a, b) => b.length - a.length)

/**
 * 규칙으로 안 되는 제목은 여기 적는다.
 * "치커리샐러드와 올리브 마늘 소스"처럼 「A와 B」 구조가 20건쯤 있는데,
 * 앞부분을 자르는 규칙을 만들었다가 "순두부 사과 소스"가 "순두부 사"로 망가졌다.
 * ('사과'의 '과'를 조사로 오인) 20건이면 규칙보다 손으로 적는 편이 안전하다.
 */
const MANUAL: Record<string, string> = {
  '치커리샐러드와 올리브 마늘 소스': '치커리 샐러드',
  '브로콜리 컬리플라워 샐러드와 두유 요거트 소스': '브로콜리 샐러드',
  '건강그린 샐러드와 고소한 두유드레싱': '그린 샐러드',
  '구운 닭고기 샐러드와 저나트륨 과일 드레싱': '닭고기 샐러드',
  '오징어보쌈과 저나트륨 된장소스': '오징어보쌈',
  '사과와 양파를 곁들인 돼지등심 요리': '돼지등심 요리',
  '레몬, 파슬리 빵가루를 입힌 도미': '도미 구이',
  '두부선과 저나트륨 겨자 간장소스': '두부선',
  '방울토마토를 곁들인 너비아니구이와 쌈밥': '너비아니구이',
  '콩국물소스를 곁들인 게살 냉채': '게살 냉채',
}

/** 제목에서 요리 이름만 뽑는다 */
export function dishName(title: string): string {
  const t = title.replace(/\([^)]*\)/g, '').trim()
  if (MANUAL[title]) return MANUAL[title]
  if (MANUAL[t]) return MANUAL[t]

  // 이미 짧으면 그대로 쓴다. 대부분이 여기에 해당한다
  if (t.replace(/\s/g, '').length <= 12) return t

  const last = t.split(/\s+/).at(-1) ?? t
  // 3자 미만이면 '찜', '샐러드'처럼 너무 뭉뚱그려져 검색이 안 된다
  if (last.length >= 3 && DISH_SUFFIX.some((d) => last.endsWith(d))) return last
  return t
}

/** 유튜브 검색어. '만들기'를 붙여야 먹방·식당 영상 대신 레시피가 위로 온다 */
export function youtubeQuery(title: string): string {
  return `${dishName(title)} 만들기`
}

export function youtubeSearchUrl(title: string): string {
  return `https://www.youtube.com/results?search_query=${encodeURIComponent(youtubeQuery(title))}`
}
